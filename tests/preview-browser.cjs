const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true, executablePath:process.env.CHROME_PATH});
 const page=await browser.newPage({viewport:{width:1440,height:1250},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/preview/api/status', route => route.fulfill({ json: { broadcast: { username: 'Blacky..', title: 'Beta assombrado', figure: 'hd-180-1.ch-210-66' } } }));
 await page.goto('http://127.0.0.1:4187/preview/');
 await page.waitForFunction(()=>presenter.username==='Blacky..');
 const card=page.locator('#compact');
 await card.locator('.body').waitFor();
 assert.equal(await card.locator('header,.mini,.collapse').count(),0);
 assert.equal(await card.getByRole('link',{name:'Abrir site da Tabblet'}).getAttribute('href'),'https://tabblet.net/');
 await card.locator('#channel').selectOption('7');
 await card.locator('.volume').fill('0.12');
 await page.waitForTimeout(180);
 await page.reload();
 assert.equal(await card.locator('.volume').inputValue(),'0.12');
 assert.equal(await card.locator('#channel').inputValue(),'7');
 await page.waitForFunction(()=>presenter.username==='Blacky..');
 await page.locator('#live').click();
 assert.equal(await card.locator('.title').textContent(),'Blacky..');
 assert.match(await card.locator('.avatar').getAttribute('src'), /headonly=1/);
 assert.equal(await card.locator('.avatar').getAttribute('alt'), 'Cabeça de Blacky..');
 assert.equal(await card.locator('#channel').isVisible(),false);
 assert.equal(await card.getByRole('button',{name:'Seguir locutor no hotel'}).getAttribute('title'),'Seguir locutor no hotel');
 assert.equal(await card.locator('.presenter-row .follow').isVisible(),true);
 assert.equal(await card.locator('#channel').inputValue(),'7');
 await card.locator('.play').click();
 await page.locator('#live').click();
 assert.equal(await card.locator('#channel').inputValue(),'7');
 assert.equal(await card.locator('.title').isVisible(),false);
 assert.equal(await card.locator('#channel').isVisible(),true);
 assert.equal(await card.locator('.player').getAttribute('data-state'),'paused');
 await page.reload();
 assert.equal(await card.locator('.player').getAttribute('data-state'),'paused');
 await page.locator('#theme').selectOption('under-construction');
 assert.equal(await card.locator('.player').getAttribute('data-theme'),'under-construction');
 await page.locator('#theme').selectOption('halloween-construction-2026');
 await card.locator('.play').click();
 // Capture the current compact layout after restoring playback.
 await page.reload();
 await page.screenshot({path:'docs/player-concepts-desktop.png',fullPage:true});
 await page.locator('.concepts').screenshot({path:'docs/player-concepts.png'});
 for(const width of [320,375,768]){
  await page.setViewportSize({width,height:1000});
  await page.waitForTimeout(50);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`no overflow at ${width}`);
 }
 await page.screenshot({path:'docs/player-concepts-mobile.png',fullPage:true});
 await page.emulateMedia({reducedMotion:'reduce'});
 assert.deepEqual(errors,[]);
 console.log('Preview passed: channel/volume/pause persistence, live return, theme swap, 320/375/768 px, no page errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1;});
